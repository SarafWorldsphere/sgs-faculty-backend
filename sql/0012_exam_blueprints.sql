-- 0012: exam types and competitive patterns, per school.
--
-- The Auto Test screen's five test types, their blueprints and the five
-- competitive patterns were constants in the frontend
-- (Swais-faculty/src/lib/testBlueprints.js). That makes a paper's shape a
-- property of the build rather than of the school: every tenant got the same
-- marks totals and question mixes, and changing one meant a code change and a
-- deploy. A school cannot say "our class test is 15 marks, not 12.5".
--
-- These tables move that decision into the database, scoped per tenant, so
-- SGS and SSS can differ.
--
-- Shape
-- -----
--   exam_blueprint       one row per test type (weekly, ct, pt, term,
--                        competitive). Carries what the screen shows and the
--                        totals it validates against.
--   exam_blueprint_row   that type's question mix — how many of each question
--                        type and what each is worth. Separate rows rather
--                        than a JSON blob so a school can be given a new mix
--                        by inserting rows, and so the counts can be summed
--                        in SQL for num_questions.
--   exam_pattern         the competitive patterns (NTSE, NMMS, olympiads),
--                        which only prefill numbers.
--
-- The seven question types stay fixed in code. They are referenced here by
-- code ('mcq', 'short', …) because the printed paper's section order and the
-- answer-space rendering are laid out around them; making them data would
-- mean a school could add a type nothing knows how to print.
--
-- Conventions follow the rest of this schema: tenant_id NOT NULL, forced
-- row-level security with the tenant_isolation policy, and the stamp_tenant
-- trigger so callers never pass tenant_id. See notice_board.
--
-- Seeded for every existing tenant with exactly today's values, so behaviour
-- is unchanged on the day this runs.
--
-- Must run as the table owner (swaispostgres). Safe to run more than once.
--
--   psql "$DATABASE_URL" -f sql/0012_exam_blueprints.sql

BEGIN;

-- ── exam_blueprint ────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS exam_blueprint (
    blueprint_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         UUID NOT NULL,
    -- Stable id the frontend already uses: weekly, ct, pt, term, competitive.
    code              TEXT NOT NULL,
    label             TEXT NOT NULL,
    short_label       TEXT,
    note              TEXT,
    total_marks       NUMERIC(6,2) NOT NULL,
    minutes           INTEGER,
    -- 'school' or 'competitive' — the screen groups the tiles by this.
    group_name        TEXT NOT NULL DEFAULT 'school',
    -- What gets recorded on the assessment when the paper is saved.
    exam_type         TEXT,
    -- PT-1..PT-4 and the like; null when a type is not numbered.
    numbered          JSONB,
    display_seq       INTEGER NOT NULL DEFAULT 0,
    is_active         BOOLEAN NOT NULL DEFAULT true,
    created_datetime  TIMESTAMPTZ DEFAULT now(),
    modified_datetime TIMESTAMPTZ,
    record_status     TEXT DEFAULT 'Active',
    version_no        INTEGER DEFAULT 1
);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='exam_blueprint_tenant_code_key') THEN
        ALTER TABLE exam_blueprint ADD CONSTRAINT exam_blueprint_tenant_code_key UNIQUE (tenant_id, code);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='exam_blueprint_tenant_id_key') THEN
        ALTER TABLE exam_blueprint ADD CONSTRAINT exam_blueprint_tenant_id_key UNIQUE (tenant_id, blueprint_id);
    END IF;
END $$;

-- ── exam_blueprint_row ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS exam_blueprint_row (
    row_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    UUID NOT NULL,
    blueprint_id BIGINT NOT NULL,
    -- One of the seven fixed question types.
    question_type TEXT NOT NULL,
    question_count INTEGER NOT NULL CHECK (question_count >= 0),
    marks_each     NUMERIC(5,2) NOT NULL CHECK (marks_each >= 0),
    display_seq    INTEGER NOT NULL DEFAULT 0
);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='exam_blueprint_row_blueprint_fk') THEN
        ALTER TABLE exam_blueprint_row
            ADD CONSTRAINT exam_blueprint_row_blueprint_fk
            FOREIGN KEY (tenant_id, blueprint_id)
            REFERENCES exam_blueprint (tenant_id, blueprint_id) ON DELETE CASCADE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='exam_blueprint_row_unique') THEN
        ALTER TABLE exam_blueprint_row
            ADD CONSTRAINT exam_blueprint_row_unique UNIQUE (tenant_id, blueprint_id, question_type);
    END IF;
END $$;

-- ── exam_pattern ──────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS exam_pattern (
    pattern_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         UUID NOT NULL,
    code              TEXT NOT NULL,
    label             TEXT NOT NULL,
    -- Passed to the AI service as exam_type for a competitive paper.
    target            TEXT NOT NULL,
    question_count    INTEGER NOT NULL,
    marks_each        NUMERIC(5,2) NOT NULL DEFAULT 1,
    minutes           INTEGER,
    display_seq       INTEGER NOT NULL DEFAULT 0,
    is_active         BOOLEAN NOT NULL DEFAULT true,
    created_datetime  TIMESTAMPTZ DEFAULT now(),
    modified_datetime TIMESTAMPTZ,
    record_status     TEXT DEFAULT 'Active',
    version_no        INTEGER DEFAULT 1
);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='exam_pattern_tenant_code_key') THEN
        ALTER TABLE exam_pattern ADD CONSTRAINT exam_pattern_tenant_code_key UNIQUE (tenant_id, code);
    END IF;
END $$;

-- ── tenant isolation, exactly as notice_board has it ──────────────────────
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['exam_blueprint','exam_blueprint_row','exam_pattern'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON %I '
            'USING (tenant_id = (SELECT platform.current_tenant_id())) '
            'WITH CHECK (tenant_id = (SELECT platform.current_tenant_id()))', t);
        EXECUTE format('DROP TRIGGER IF EXISTS stamp_tenant ON %I', t);
        EXECUTE format(
            'CREATE TRIGGER stamp_tenant BEFORE INSERT OR UPDATE ON %I '
            'FOR EACH ROW EXECUTE FUNCTION platform.stamp_tenant_id()', t);
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS ix_exam_blueprint_tenant_active
    ON exam_blueprint (tenant_id, is_active, display_seq);
CREATE INDEX IF NOT EXISTS ix_exam_pattern_tenant_active
    ON exam_pattern (tenant_id, is_active, display_seq);

-- ── seed: today's values, for every tenant that exists ────────────────────
--
-- Written as a loop over platform.tenants with the tenant set explicitly,
-- because the policies above are FORCE and the trigger reads app.tenant_id.
DO $$
DECLARE
    t  RECORD;
    bp RECORD;
    bid BIGINT;
BEGIN
FOR t IN SELECT tenant_id FROM platform.tenants LOOP
    PERFORM set_config('app.tenant_id', t.tenant_id::text, true);

    FOR bp IN
        SELECT * FROM (VALUES
          ('weekly','Weekly test','weekly test','10 marks · 1 chapter',10.0,30,'school','Weekly',NULL::jsonb,1),
          ('ct','Class test (CT)','class test','12.5 marks · 1–2 chapters',12.5,30,'school','CT',NULL,2),
          ('pt','Periodic test (PT)','periodic test','50 marks · 2–3 chapters',50.0,60,'school',NULL,
             '["PT-1","PT-2","PT-3","PT-4"]'::jsonb,3),
          ('term','Term exam','term exam','80 marks · full syllabus',80.0,150,'school','Term',NULL,4),
          ('competitive','Competitive test','competitive test','Multiple choice only',50.0,45,'competitive',NULL,NULL,5)
        ) AS v(code,label,short_label,note,total_marks,minutes,group_name,exam_type,numbered,display_seq)
    LOOP
        INSERT INTO exam_blueprint (code,label,short_label,note,total_marks,minutes,group_name,exam_type,numbered,display_seq)
        VALUES (bp.code,bp.label,bp.short_label,bp.note,bp.total_marks,bp.minutes,bp.group_name,bp.exam_type,bp.numbered,bp.display_seq)
        ON CONFLICT (tenant_id, code) DO NOTHING;
    END LOOP;

    -- the question mix for each, in printed-paper order
    FOR bp IN
        SELECT * FROM (VALUES
          ('weekly','mcq',5,1.0,1),      ('weekly','truefalse',3,1.0,2), ('weekly','short',1,2.0,3),
          ('ct','mcq',5,1.0,1),          ('ct','fill',5,1.0,2),          ('ct','short',1,2.5,3),
          ('pt','mcq',10,1.0,1),         ('pt','fill',5,1.0,2),          ('pt','truefalse',5,1.0,3),
          ('pt','oneword',5,1.0,4),      ('pt','match',1,5.0,5),         ('pt','short',5,2.0,6),
          ('pt','long',2,5.0,7),
          ('term','mcq',15,1.0,1),       ('term','fill',5,1.0,2),        ('term','truefalse',5,1.0,3),
          ('term','oneword',5,1.0,4),    ('term','match',1,5.0,5),       ('term','short',10,2.0,6),
          ('term','long',5,5.0,7),
          ('competitive','mcq',50,1.0,1)
        ) AS v(code,question_type,question_count,marks_each,display_seq)
    LOOP
        -- Scoped by tenant_id explicitly, not left to row-level security.
        -- This script runs as the table owner, who is a superuser, and a
        -- superuser bypasses RLS even when it is FORCEd — so without this
        -- the lookup saw every school's rows and returned the first
        -- tenant's blueprint_id for the second tenant, which the foreign
        -- key then rejected.
        SELECT blueprint_id INTO bid
        FROM exam_blueprint
        WHERE code = bp.code AND tenant_id = t.tenant_id;
        IF bid IS NOT NULL THEN
            INSERT INTO exam_blueprint_row (blueprint_id,question_type,question_count,marks_each,display_seq)
            VALUES (bid,bp.question_type,bp.question_count,bp.marks_each,bp.display_seq)
            ON CONFLICT (tenant_id, blueprint_id, question_type) DO NOTHING;
        END IF;
    END LOOP;

    FOR bp IN
        SELECT * FROM (VALUES
          ('ntse','NTSE — stage 1 practice','NTSE',50,1.0,45,1),
          ('nmms','NMMS practice','NMMS',45,1.0,45,2),
          ('science','Science olympiad','Science',35,1.0,60,3),
          ('maths','Maths olympiad','Maths',35,1.0,60,4),
          ('custom','Custom','Custom',50,1.0,45,5)
        ) AS v(code,label,target,question_count,marks_each,minutes,display_seq)
    LOOP
        INSERT INTO exam_pattern (code,label,target,question_count,marks_each,minutes,display_seq)
        VALUES (bp.code,bp.label,bp.target,bp.question_count,bp.marks_each,bp.minutes,bp.display_seq)
        ON CONFLICT (tenant_id, code) DO NOTHING;
    END LOOP;
END LOOP;
END $$;

COMMIT;

