-- 0010_demo_missing_objects.sql
--
-- Creates the four tables and eight columns the ORM models expect but the
-- saraswati database does not have. Diagnosed 2026-11-27 against
-- swais-db-test-env .../saraswati, which serves sgs-test and sss-test.
--
-- RUN AS swaispostgres. The application user saas_app has no CREATE on
-- public (has_schema_privilege -> false) and is not a member of
-- swaispostgres, so it cannot apply this.
--
-- Conventions copied from the existing tables, not from alembic:
--   * tenant_id uuid NOT NULL on every tenant-scoped table
--   * ROW LEVEL SECURITY enabled AND forced
--   * policy tenant_isolation USING (tenant_id = platform.current_tenant_id())
--   * privileges granted to role saraswati_app (saas_app inherits them)
--   * bigint GENERATED BY DEFAULT AS IDENTITY primary keys
--
-- Do NOT substitute `alembic upgrade head` for this. alembic 0009 creates
-- sgs_timetable and sgs_period_master WITHOUT tenant_id and without RLS,
-- which would silently break isolation on a two-tenant database.
--
-- Models declare ticket_id/message_id as Integer; bigint is used here to
-- match every other primary key in this schema. Reads are unaffected.

BEGIN;

-- ── 1. sgs_period_master — bell schedule (app/models/timetable.py) ──────────
CREATE TABLE IF NOT EXISTS sgs_period_master (
    period_id     bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     uuid         NOT NULL,
    academic_year varchar(9)   NOT NULL,
    schedule_type varchar(10)  NOT NULL DEFAULT 'full',
    period_no     integer      NOT NULL,
    period_label  varchar(50)  NOT NULL,
    start_time    time         NOT NULL,
    end_time      time         NOT NULL,
    is_teaching   boolean      NOT NULL DEFAULT true,
    record_status varchar(20)  DEFAULT 'Active',
    created_at    timestamp,
    CONSTRAINT uq_period_master
        UNIQUE (tenant_id, academic_year, schedule_type, period_no)
);

-- ── 2. sgs_timetable — the weekly grid (app/models/timetable.py) ────────────
-- tenant_id leads every unique key and index: without it two tenants would
-- collide on the same (year, class, section, day, period) slot.
CREATE TABLE IF NOT EXISTS sgs_timetable (
    timetable_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     uuid         NOT NULL,
    academic_year varchar(9)   NOT NULL,
    class_id      bigint       NOT NULL,
    section       varchar(10)  NOT NULL,
    day_of_week   integer      NOT NULL,
    period_no     integer      NOT NULL,
    subject_name  varchar(150) NOT NULL,
    teacher_id    varchar(50)  NOT NULL,
    record_status varchar(20)  DEFAULT 'Active',
    created_at    timestamp,
    updated_at    timestamp,
    CONSTRAINT uq_timetable_slot
        UNIQUE (tenant_id, academic_year, class_id, section, day_of_week, period_no),
    CONSTRAINT ck_timetable_day    CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_timetable_period CHECK (period_no > 0)
);

CREATE INDEX IF NOT EXISTS ix_sgs_timetable_class
    ON sgs_timetable (tenant_id, academic_year, class_id, section);
CREATE INDEX IF NOT EXISTS ix_sgs_timetable_teacher
    ON sgs_timetable (tenant_id, academic_year, teacher_id);

-- ── 3. sgs_support_tickets — Messages threads (app/models/conversation.py) ──
CREATE TABLE IF NOT EXISTS sgs_support_tickets (
    ticket_id         bigint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         uuid      NOT NULL,
    ticket_number     varchar(100),
    parent_id         integer,
    student_id        bigint,
    subject           varchar(500),
    category          varchar(100),
    status            varchar(50) DEFAULT 'OPEN',
    recipient_name    varchar(255),
    recipient_user_id bigint,
    created_at        timestamp,
    updated_at        timestamp
);

CREATE INDEX IF NOT EXISTS ix_sgs_support_tickets_parent
    ON sgs_support_tickets (tenant_id, parent_id);
CREATE INDEX IF NOT EXISTS ix_sgs_support_tickets_student
    ON sgs_support_tickets (tenant_id, student_id);
CREATE INDEX IF NOT EXISTS ix_sgs_support_tickets_recipient
    ON sgs_support_tickets (tenant_id, recipient_user_id);

-- ── 4. sgs_ticket_messages — replies within a thread ────────────────────────
CREATE TABLE IF NOT EXISTS sgs_ticket_messages (
    message_id  bigint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   uuid      NOT NULL,
    ticket_id   bigint,
    sender_type varchar(50),
    sender_name varchar(255),
    message     text,
    created_at  timestamp,
    is_read     boolean   DEFAULT false
);

CREATE INDEX IF NOT EXISTS ix_sgs_ticket_messages_ticket
    ON sgs_ticket_messages (tenant_id, ticket_id);

-- ── 5. exam_master — columns the model reads, ORDER BY start_date ───────────
ALTER TABLE exam_master
    ADD COLUMN IF NOT EXISTS start_date       date,
    ADD COLUMN IF NOT EXISTS end_date         date,
    ADD COLUMN IF NOT EXISTS created_datetime timestamp,
    ADD COLUMN IF NOT EXISTS version_no       integer;

-- ── 6. assignment_results — the only fault currently live in the logs ───────
ALTER TABLE assignment_results
    ADD COLUMN IF NOT EXISTS submission_text text,
    ADD COLUMN IF NOT EXISTS submission_link varchar(1000),
    ADD COLUMN IF NOT EXISTS marks_obtained  numeric,
    ADD COLUMN IF NOT EXISTS total_marks     numeric;

-- ── 7. Tenancy and privileges for the four new tables ───────────────────────
-- Identical to the policy on exam_master. FORCE applies RLS to the owner too,
-- so swaispostgres is also confined to one tenant per connection.
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'sgs_period_master',
        'sgs_timetable',
        'sgs_support_tickets',
        'sgs_ticket_messages'
    ] LOOP
        EXECUTE format('ALTER TABLE %I OWNER TO swaispostgres', t);
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('ALTER TABLE %I FORCE  ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
        EXECUTE format(
            'CREATE POLICY tenant_isolation ON %I '
            'USING (tenant_id = (SELECT platform.current_tenant_id()))', t);
        EXECUTE format(
            'GRANT SELECT, INSERT, UPDATE, DELETE ON %I TO saraswati_app', t);
    END LOOP;
END $$;

COMMIT;

